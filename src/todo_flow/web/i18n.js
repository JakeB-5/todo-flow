const catalogs = {
  en: {},
  ko: koreanMessages,
  ja: Object.fromEntries(Object.entries(additionalMessages).map(([key, values]) => [key, values[0]])),
  'zh-CN': Object.fromEntries(Object.entries(additionalMessages).map(([key, values]) => [key, values[1]]))
};
const localeTags = {en:'en-US', ko:'ko-KR', ja:'ja-JP', 'zh-CN':'zh-CN'};
let language = 'en';
let languageProject = '';
function localeTag() { return localeTags[language]; }
function tr(message, values = {}) {
  const messages = catalogs[language];
  const text = String(Object.hasOwn(messages, message) ? messages[message] : message);
  return text.replace(/\{(\w+)\}/g, (match, key) => values[key] ?? match);
}
function applyLanguage(value) {
  language = Object.hasOwn(catalogs, value) ? value : 'en';
  document.documentElement.lang = language;
  for (const element of document.querySelectorAll('[data-i18n]')) element.textContent = tr(element.dataset.i18n);
  for (const attribute of ['aria-label', 'title', 'placeholder']) {
    for (const element of document.querySelectorAll('[data-i18n-' + attribute + ']')) {
      element.setAttribute(attribute, tr(element.getAttribute('data-i18n-' + attribute)));
    }
  }
  document.getElementById('language').value = language;
  refreshLabels();
}
function useProjectLanguage(project) {
  if (languageProject === project.key) return;
  languageProject = project.key;
  let saved;
  try { saved = localStorage.getItem('todo-flow.language.' + languageProject); } catch { /* Storage can be disabled. */ }
  applyLanguage(Object.hasOwn(catalogs, saved) ? saved : project.language);
}
function saveDisplayLanguage(value) {
  applyLanguage(value);
  try { localStorage.setItem('todo-flow.language.' + languageProject, language); } catch { /* Switching still works. */ }
}
